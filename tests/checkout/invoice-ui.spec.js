const { test, expect } = require('@playwright/test');
const fs = require('node:fs');
const source = fs.readFileSync('checkout.html', 'utf8');
const stateController = fs.readFileSync('js/pages/checkout/estado-navegacion-checkout.js', 'utf8');
const handlers = source.slice(source.indexOf('const invoiceFieldsEl'), source.indexOf("document.getElementById('btn-step3-next').onclick"));
for (const width of [320, 390, 768, 1024, 1440, 1920]) test(`factura: selección previa, guion móvil y datos conservados (${width}px)`, async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const html = source.replace(/<script\b[\s\S]*?<\/script>/gi, '').replace('</body>', `<script>${handlers};document.querySelectorAll('.ck-panel').forEach(el=>el.classList.toggle('active',el.id==='panel-2'));document.documentElement.classList.remove('tt-color-scheme-pending','tt-store-gate-pending');document.body.classList.add('tt-checkout-maintenance');</script><script>${stateController}</script></body>`);
  await page.route('**/checkout?invoice-fixture=1', route => route.fulfill({ contentType: 'text/html', body: html }));
  await page.setViewportSize({ width, height: 900 });
  await page.goto('/checkout?invoice-fixture=1');
  const checkbox = page.locator('#ck-wants-invoice');
  const type = page.locator('#ck-taxpayer-type');
  const name = page.locator('#ck-razon-social');
  const ruc = page.locator('#ck-ruc');
  const hyphen = page.getByRole('button', { name: 'Agregar guion al RUC' });
  await expect(page.getByText('Quiero factura', { exact: true })).toBeVisible();
  await expect(page.locator('#ck-invoice-fields')).toBeHidden();
  await checkbox.check();
  await expect(checkbox).toHaveAttribute('aria-expanded', 'true');
  await expect(type).toHaveAttribute('required', '');
  await expect(name).toBeDisabled();
  await expect(ruc).toBeDisabled();
  await expect(hyphen).toBeDisabled();
  await page.locator('#error-2').evaluate(el => { el.textContent = 'Elegí el tipo de contribuyente para tu factura.'; el.classList.add('show'); });
  await type.selectOption('fisica');
  await expect(page.locator('#error-2')).toHaveText('');
  await expect(name).toBeEnabled();
  await expect(ruc).toBeEnabled();
  await expect(page.locator('label[for="ck-razon-social"]')).toHaveText('Nombre y apellido para la factura *');
  await name.fill('Persona de Prueba');
  await ruc.fill('4420420');
  await hyphen.click();
  await expect(ruc).toBeFocused();
  await expect(ruc).toHaveValue('4420420-');
  await expect(hyphen).toBeDisabled();
  await ruc.press('5');
  await expect(ruc).toHaveValue('4420420-5');
  await type.selectOption('');
  await expect(name).toBeDisabled();
  await expect(ruc).toBeDisabled();
  await expect(ruc).toHaveValue('4420420-5');
  await type.selectOption('juridica');
  await expect(page.locator('label[for="ck-razon-social"]')).toHaveText('Razón social *');
  await ruc.fill('80012345');
  await hyphen.click();
  await ruc.press('6');
  await expect(ruc).toHaveValue('80012345-6');
  await ruc.fill('123');
  await hyphen.click();
  await expect(ruc).toHaveValue('123-');
  await ruc.fill('80012345-6');
  await expect(hyphen).toBeDisabled();
  await page.evaluate(() => window.TintinCheckoutState.persist());
  await page.reload();
  await expect(type).toHaveValue('juridica');
  await expect(ruc).toBeEnabled();
  await expect(ruc).toHaveValue('80012345-6');
  await checkbox.uncheck();
  await expect(ruc).not.toHaveAttribute('required');
  await expect(ruc).toBeDisabled();
  await expect(page.locator('#ck-invoice-fields')).toBeHidden();
  await checkbox.check();
  await expect(name).toHaveValue('Persona de Prueba');
  await expect(ruc).toHaveValue('80012345-6');
  await expect(ruc).toBeEnabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  expect(errors).toEqual([]);
});
